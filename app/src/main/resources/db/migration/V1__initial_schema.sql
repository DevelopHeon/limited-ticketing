CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uk_member_external_id UNIQUE (external_id)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    benefit_description VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE sale_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    sale_price NUMERIC(19, 2) NOT NULL,
    sale_starts_at TIMESTAMP NOT NULL,
    sale_ends_at TIMESTAMP NOT NULL,
    purchase_limit_per_member INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_product_id BIGINT NOT NULL,
    available_quantity BIGINT NOT NULL,
    reserved_quantity BIGINT NOT NULL,
    sold_quantity BIGINT NOT NULL,
    CONSTRAINT uk_inventory_sale_product UNIQUE (sale_product_id)
);

CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    sale_product_id BIGINT NOT NULL,
    active_purchase_key VARCHAR(100),
    purchase_price NUMERIC(19, 2) NOT NULL,
    quantity INTEGER NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uk_purchase_active_purchase_key UNIQUE (active_purchase_key)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL,
    payment_request_key VARCHAR(100) NOT NULL,
    payment_amount NUMERIC(19, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    approved_at TIMESTAMP,
    CONSTRAINT uk_payment_request_key UNIQUE (payment_request_key)
);
